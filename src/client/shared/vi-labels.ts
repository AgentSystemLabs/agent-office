export function vietnameseLabel(value: string): string {
  const plain = value.trim();
  let translated = VI[plain];
  if (!translated) {
    // Preserve emoji prefixes and keyboard shortcut suffixes on otherwise exact UI labels.
    for (const [en, vi] of Object.entries(VI)) {
      if (plain.endsWith(en) && /^[^\p{L}\p{N}]*$/u.test(plain.slice(0, -en.length))) {
        translated = plain.slice(0, -en.length) + vi; break;
      }
    }
  }
  if (!translated) translated = plain.replace(/^✨ Hire a worker at Desk (\d+)$/, '✨ Tạo AI tại bàn $1');
  if (translated === plain) translated = plain.replace(/^(\D*)(\d+) needs you$/, '$1$2 AI đang chờ anh').replace(/^(.*) needs you$/, '$1 đang chờ anh');
  if (translated === plain && plain.includes(' · ')) {
    translated = plain.split(' · ').map(part => VI[part] ?? part).join(' · ');
  }
  if (translated === plain) return value;
  if (!translated) return value;
  return value.replace(plain, translated);
}
